#include "backend/kernel_runtime.h"

void re0_kernel_hooks_emit(Re0Buffer *out) {
    if (!out) return;
    re0_buffer_write_str(out,
        "#ifndef __REO_MAX_CALL_DEPTH\n#define __REO_MAX_CALL_DEPTH 1024\n#endif\n"
        "#if __REO_MAX_CALL_DEPTH < 1 || __REO_MAX_CALL_DEPTH > UINT32_MAX\n"
        "#error invalid kernel call depth limit\n#endif\n"
        "enum { __REO_KERNEL_MAX_DIAGNOSTIC = 4096 };\n"
        "__attribute__((weak)) void __reo_kernel_diagnostic(const char *, size_t);\n"
        "__attribute__((weak)) void __reo_kernel_abort(void);\n"
        "__attribute__((weak)) void *__reo_kernel_alloc(size_t);\n"
        "__attribute__((weak)) void __reo_kernel_free_impl(void *);\n"
        "__attribute__((weak)) void *__reo_kernel_depth_enter(uint32_t);\n"
        "__attribute__((weak)) void __reo_kernel_depth_leave(void *);\n"
        "_Noreturn static void __reo_kernel_fail_message(const char *message) {\n"
        "    if (!message) message = \"kernel failure\";\n"
        "    size_t length = 0;\n"
        "    while (length < __REO_KERNEL_MAX_DIAGNOSTIC && message[length]) ++length;\n"
        "    if (__reo_kernel_diagnostic) __reo_kernel_diagnostic(message, length);\n"
        "    if (__reo_kernel_abort) __reo_kernel_abort();\n"
        "    __builtin_trap();\n"
        "}\n"
        "_Noreturn static void __reo_kernel_fail(void) { __reo_kernel_fail_message(\"kernel failure\"); }\n"
        "static void *malloc(size_t n) {\n"
        "    if (!n) return (void *)0;\n"
        "    if (!__reo_kernel_alloc || !__reo_kernel_free_impl)\n"
        "        __reo_kernel_fail_message(\"kernel allocator hooks are not installed as a pair\");\n"
        "    return __reo_kernel_alloc(n);\n"
        "}\n"
        "static void free(void *p) {\n"
        "    if (!p) return;\n"
        "    if (!__reo_kernel_free_impl) __reo_kernel_fail_message(\"kernel free hook is not installed\");\n"
        "    __reo_kernel_free_impl(p);\n"
        "}\n"
        "typedef struct { void *context; bool active; } __reo_depth_guard_t;\n"
        "static __reo_depth_guard_t __reo_depth_enter(void) {\n"
        "    __reo_depth_guard_t g = { (void *)0, false };\n"
        "    if (!__reo_kernel_depth_enter && !__reo_kernel_depth_leave) return g;\n"
        "    if (!__reo_kernel_depth_enter || !__reo_kernel_depth_leave)\n"
        "        __reo_kernel_fail_message(\"kernel depth hooks are not installed as a pair\");\n"
        "    g.context = __reo_kernel_depth_enter((uint32_t)__REO_MAX_CALL_DEPTH); g.active = true;\n"
        "    return g;\n"
        "}\n"
        "static void __reo_depth_leave(__reo_depth_guard_t *g) {\n"
        "    if (g->active) __reo_kernel_depth_leave(g->context);\n"
        "}\n"
        "#define __REO_DEPTH_GUARD __reo_depth_guard_t __reo_dg __attribute__((cleanup(__reo_depth_leave))) = __reo_depth_enter()\n"
        "#define abort() __reo_kernel_fail()\n");
}
